#!/usr/bin/env python3
"""Merge the per-batch files in facts/<topic>/ into facts/<topic>/_merged.md.

    python3 scripts/build_facts.py            write every _merged.md
    python3 scripts/build_facts.py --check    exit 1 if any _merged.md is out of date

Facts are grouped by subject and every line is tagged with its source file. Exact duplicates are
flagged. The output is generated and must never be edited by hand. Uses no tokens.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mdutil import norm, read_text, split_front_matter  # noqa: E402

HEADER = "<!-- GENERATED by scripts/build_facts.py. Do not edit by hand: edit the batch files and re-run. -->"
SUBJECT_RE = re.compile(r"^(.{1,80}?)\s*[:：]\s+(.*)$")
NO_SUBJECT = "(no subject)"


def parse_batch(path):
    text = read_text(path)
    fm, body, _ = split_front_matter(text)
    fm = fm or {}
    kind, facts, other = "fact", [], {"clarify": [], "flag": [], "oos": []}
    for line in body.split("\n"):
        if line.startswith("## "):
            h = line[3:].strip().casefold()
            if h.startswith("needs clarification"):
                kind = "clarify"
            elif h.startswith("flagged for checking"):
                kind = "flag"
            elif h.startswith("out of scope"):
                kind = "oos"
            else:
                kind = "fact"
            continue
        m = re.match(r"^\s*[-*]\s+(.*\S)\s*$", line)
        if not m:
            continue
        item = m.group(1)
        if kind == "fact":
            sm = SUBJECT_RE.match(item)
            subject, rest = (sm.group(1), sm.group(2)) if sm else (NO_SUBJECT, item)
            facts.append((subject, rest))
        else:
            other[kind].append(item)
    return {"stem": path.stem, "fm": fm, "facts": facts, **other}


def dup_key(subject, text):
    stripped = re.sub(r"\[L[^\]]*\]", "", text)
    return norm(subject), norm(stripped)


def build_topic(topic, batches):
    out = [HEADER, "", f"# Merged facts: {topic}", "", "## Sources", "",
           "| file | id | author | group | status | raw |", "| --- | --- | --- | --- | --- | --- |"]
    for b in batches:
        f = b["fm"]
        out.append(f"| {b['stem']} | {f.get('id', '')} | {f.get('author', '')} | {f.get('group', '')} "
                   f"| {f.get('status', '')} | {f.get('raw', '')} |")

    by_subject, first_seen, dups = {}, {}, []
    for b in batches:
        for subject, text in b["facts"]:
            key = dup_key(subject, text)
            is_dup = key in first_seen
            if is_dup:
                dups.append((subject, text, first_seen[key], b["stem"]))
            else:
                first_seen[key] = b["stem"]
            by_subject.setdefault(norm(subject), (subject, []))[1].append((text, b["stem"], is_dup))

    out += ["", "## Facts by subject"]
    for _, (subject, lines) in sorted(by_subject.items()):
        out += ["", f"### {subject}"]
        for text, stem, is_dup in lines:
            out.append(f"- {text} <{stem}>" + ("  ⚠ exact duplicate" if is_dup else ""))

    out += ["", "## Exact duplicates"]
    if dups:
        for subject, text, first, again in dups:
            plain = re.sub(r"\s*\[L[^\]]*\]", "", text)
            out.append(f"- {subject}: {plain}  (in {first} and {again})")
    else:
        out.append("- none")

    for key, title in (("clarify", "Needs clarification"), ("flag", "Flagged for checking"),
                       ("oos", "Out of scope for now (subspecialty)")):
        rows = [(b["stem"], i) for b in batches for i in b[key]]
        if not rows:
            continue
        out += ["", f"## {title}"]
        for stem in sorted({s for s, _ in rows}):
            out += ["", f"### {stem}"] + [f"- {i}" for s, i in rows if s == stem]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if out of date")
    args = ap.parse_args(argv)
    facts = Path(args.root).resolve() / "facts"
    stale = False
    for tdir in sorted(p for p in facts.iterdir() if p.is_dir()) if facts.is_dir() else []:
        files = sorted(p for p in tdir.glob("*.md") if not p.name.startswith("_"))
        if not files:
            continue
        new = build_topic(tdir.name, [parse_batch(p) for p in files])
        target = tdir / "_merged.md"
        old = target.read_text(encoding="utf-8") if target.is_file() else None
        if old == new:
            print(f"up to date: {target.relative_to(facts.parent).as_posix()}")
        elif args.check:
            print(f"OUT OF DATE: {target.relative_to(facts.parent).as_posix()}")
            stale = True
        else:
            target.write_text(new, encoding="utf-8")
            print(f"wrote: {target.relative_to(facts.parent).as_posix()}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
