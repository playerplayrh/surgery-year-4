#!/usr/bin/env python3
"""Exam mind maps: one Markdown page per organ system, built from the exam tags (never by G).

    python3 scripts/exam_mindmap.py            writes exam-map/mind-maps/<system>.md and _index.md

Each page has a Mermaid mind map (organ system -> topic -> question type, with counts) and, for
every topic, a table of its questions: set and number, cohort, question type, the subtopic (what
the question asks, never the answer) and where to read. Reads exam-map/tags/<set>.md
('- Q12 | topic | asks | subtopic | read') and INDEX.md for the organ system of each topic.
Generated pages say so at the top; edit the tags, not these pages. Standard library only.
"""
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mdutil import read_text  # noqa: E402
from validate import in_exam_map, load_topic_systems, parse_tags_full  # noqa: E402

REPO_URL = "https://github.com/playerplayrh/surgery-year-4/blob/main/"
ASKS = ["diagnosis", "investigation", "management", "complication", "basic-science", "other"]


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def cohort(code):
    m = re.match(r"mdcu(\d+)", code)
    return f"MDCU{m.group(1)}" if m else code


def collect(root):
    systems = load_topic_systems(root) or {}
    rows = []
    for tf in sorted((root / "exam-map" / "tags").glob("*.md")):
        code = tf.stem
        if code.startswith("_") or not in_exam_map(code):
            continue
        for _, q, topic, asks, sub, rd in parse_tags_full(read_text(tf)):
            rows.append({"set": code, "q": q, "topic": topic, "asks": asks, "sub": sub, "read": rd,
                         "cohort": cohort(code), "system": systems.get(topic, "Other")})
    return systems, rows


def cell(s):
    return (s or "").replace("|", "/").strip()


def page(system, rows):
    by_topic = defaultdict(list)
    for r in rows:
        by_topic[r["topic"]].append(r)
    topics = sorted(by_topic, key=lambda t: (-len(by_topic[t]), t))
    cohorts = sorted({r["cohort"] for r in rows}, key=lambda c: (len(c), c))
    out = ["---", "tags: [exam-map, mind-map]", f'organ_system: "{system}"', "status: ai-generated", "---", "",
           f"# {system}", "",
           "Generated by `scripts/exam_mindmap.py` from `exam-map/tags/`. Edit the tags, not this page.",
           f"{len(rows)} past General Sx MCQ questions ({', '.join(cohorts)}). Subtopics say what each question "
           "asks, never its answer. Read = Board Review note (BR nn) first, then Chula Surgery 1 chapter and "
           "pages. AI-made labels from student-recalled papers and student keys, unchecked: check against "
           "the textbook or your attending.", "",
           "## Mind map", "", "```mermaid", "mindmap",
           f"  root(({system}<br>{len(rows)} questions))"]
    for t in topics:
        qs = by_topic[t]
        out.append(f"    ({t} · {len(qs)})")
        c = Counter(r["asks"] for r in qs)
        for a in ASKS:
            if c[a]:
                out.append(f"      {a} · {c[a]}")
    out += ["```", ""]
    for t in topics:
        qs = sorted(by_topic[t], key=lambda r: (-int(r["cohort"][4:] or 0) if r["cohort"][4:].isdigit() else 0,
                                                r["set"], r["q"]))
        asked = sorted({r["cohort"] for r in qs}, key=lambda c: (len(c), c))
        reads = Counter(x.strip() for r in qs for x in r["read"].split(";") if x.strip())
        out += [f"## {t}", "",
                f"{len(qs)} questions · asked by {', '.join(asked)} · "
                + ", ".join(f"{a} {n}" for a, n in Counter(r['asks'] for r in qs).most_common()), "",
                "Most cited reading: " + "; ".join(x for x, _ in reads.most_common(4)), "",
                "| Question | Type | What it asks | Read |", "| --- | --- | --- | --- |"]
        for r in qs:
            link = f"[{r['set'].replace('-mcq', '')} Q{r['q']}]({REPO_URL}exams/{r['set']}/exam.md)"
            out.append(f"| {link} | {r['asks']} | {cell(r['sub']) or 'not labelled yet'} | {cell(r['read'])} |")
        out.append("")
    return "\n".join(out) + "\n"


def main():
    root = Path(__file__).resolve().parent.parent
    systems, rows = collect(root)
    order = list(dict.fromkeys(systems.values())) + ["Other"]
    by_sys = defaultdict(list)
    for r in rows:
        by_sys[r["system"]].append(r)
    outdir = root / "exam-map" / "mind-maps"
    outdir.mkdir(parents=True, exist_ok=True)
    for old in outdir.glob("*.md"):
        old.unlink()
    index = ["---", "tags: [exam-map, mind-map]", "status: ai-generated", "---", "", "# Exam mind maps", "",
             "Generated by `scripts/exam_mindmap.py` from `exam-map/tags/`. "
             f"{len(rows)} past General Sx MCQ questions, by organ system (never by G). "
             "Open a system for its mind map and a table of every question with what it asks and where to read.", ""]
    for s in sorted(by_sys, key=lambda s: -len(by_sys[s])):
        name = f"{slug(s)}.md"
        (outdir / name).write_text(page(s, by_sys[s]), encoding="utf-8")
        index.append(f"- [{s}]({name}) · {len(by_sys[s])}")
    (outdir / "_index.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print(f"wrote {len(by_sys)} system pages and _index.md to {outdir.relative_to(root)} ({len(rows)} questions)")


if __name__ == "__main__":
    main()
